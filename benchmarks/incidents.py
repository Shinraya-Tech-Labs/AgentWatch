@dataclass(frozen=True)
class Results:
    true_positives: int
    false_negatives: int
    false_positives: int
    true_negatives: int
    latencies_ms: tuple[float, ...]

    @property
    def recall(self) -> float:
        return self.true_positives / (self.true_positives + self.false_negatives)

    @property
    def precision(self) -> float:
        denom = self.true_positives + self.false_positives
        return self.true_positives / denom if denom else 1.0

    @property
    def false_positive_rate(self) -> float:
        return self.false_positives / (self.false_positives + self.true_negatives)

    def percentile(self, p: float) -> float:
        ordered = sorted(self.latencies_ms)
        return ordered[min(len(ordered) - 1, int(round(p * (len(ordered) - 1))))]


def run(corpus: tuple[Case, ...] = CORPUS) -> Results:
    """Evaluate every case through the default pipeline, one fresh session each."""
    pipeline = ProtectionPipeline()
    tp = fn = fp = tn = 0
    latencies: list[float] = []

    for case in corpus:
        action = ToolAction(
            agent_id="benchmark-agent",
            session_id=f"benchmark-{case.case_id}",
            tool="bash",
            arguments={"command": case.command},
        )
        started = time.perf_counter()
        decision = pipeline.evaluate(action, wait_for_approval=False)
        latencies.append((time.perf_counter() - started) * 1000.0)

        blocked = decision.verdict.value != "allow"
        if case.label == "attack":
            tp += blocked
            fn += not blocked
        else:
            fp += blocked
            tn += not blocked

    return Results(tp, fn, fp, tn, tuple(latencies))


def metric_rows(results: Results) -> list[str]:
    """Deterministic rows: every verdict is decided locally, so these must not drift."""
    return [
        "| Metric | Value |",
        "|---|---|",
        f"| Attack cases blocked (recall) | {results.recall:.1%} ({results.true_positives}/{len(CORPUS) // 2}) |",
        f"| Benign cases wrongly blocked (false-positive rate) | {results.false_positive_rate:.1%} ({results.false_positives}/{len(CORPUS) // 2}) |",
        f"| Precision | {results.precision:.1%} |",
    ]


def latency_rows(results: Results) -> list[str]:
    """Timing is machine-dependent, so it is shown but never compared across runs."""
    return [
        f"| Inline latency p50 / p95 | {results.percentile(0.50):.1f} ms / {results.percentile(0.95):.1f} ms |",
        f"| Mean latency | {mean(results.latencies_ms):.1f} ms |",
    ]


def markdown(results: Results) -> str:
    return "\n".join(metric_rows(results) + latency_rows(results))


def block(results: Results) -> str:
    return f"{BEGIN_MARKER}\n{markdown(results)}\n{END_MARKER}"


def _readme() -> Path:
    return Path(__file__).resolve().parents[1] / "README.md"


def write_readme(results: Results) -> None:
    path = _readme()
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN_MARKER) + r".*?" + re.escape(END_MARKER), re.S)
    if not pattern.search(text):
        raise SystemExit(f"README.md has no benchmark block; add {BEGIN_MARKER} … {END_MARKER}")
    path.write_text(pattern.sub(block(results), text), encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the README table")
    parser.add_argument(
        "--check", action="store_true", help="fail if the gates or README are stale"
    )
    args = parser.parse_args(argv)

    results = run()
    print(markdown(results))

    if args.write:
        write_readme(results)
        print("\nREADME.md updated.")

    failures = []
    if results.recall < MIN_RECALL:
        failures.append(f"recall {results.recall:.1%} < {MIN_RECALL:.0%}")
    if args.check:
        readme = _readme().read_text(encoding="utf-8")
        missing = [row for row in metric_rows(results) if row not in readme]
        if missing:
            failures.append("README.md benchmark table is stale; run --write")

    for failure in failures:
        print(f"FAIL: {failure}", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
