"""Incident corpus benchmark: block rate, false-positive rate, inline latency.

Run::

    python -m benchmarks.incidents --write    # regenerate the README table
    python -m benchmarks.incidents --check    # CI gate: numbers and README must still hold

The corpus is 40 attack-shaped tool calls and 40 benign ones that *look* dangerous.
The benign half is the point: a guardrail's false-positive rate decides whether
anyone keeps it installed, and a corpus of only `cat file.txt` negatives proves
nothing. Attacks are instances of documented agent failure classes (database
deletion, credential exfiltration, reverse shells, destructive infrastructure
changes), not verbatim incidents; each case names the class it represents.

Everything here is deterministic and local: the default ``ProtectionPipeline``
config, no API keys, no network. Latency is measured in-process on the same
machine as the test run, so treat it as order-of-magnitude, not a hardware SLA.
"""

